  /// Busca en el catálogo por id (`null` si no existe o si no hay id, que es
  /// lo que guarda la pref cuando el usuario dejó el tema en Automático).
  static ThemeVariant? byId(String? id) {
    if (id == null || id.isEmpty) return null;
    for (final variant in builtIn) {
      if (variant.id == id) return variant;
    }
    return null;
  }

  /// Variantes de un tipo, en el orden del catálogo (secciones Claro/Oscuro
  /// del selector).
  static List<ThemeVariant> ofKind(ThemeVariantKind kind) =>
      builtIn.where((variant) => variant.kind == kind).toList();
}
