/// Catálogo de las 61 variantes de tema del cliente desktop (33 oscuras + 28
/// claras), con la paleta resuelta de cada una.
///
/// Port de `openher-flutter-desktop/lib/ui/core/theme_variants.dart`, que a su
/// vez es port de `web/src/context/themeVariant.tsx` y de los JSON de
/// `web/public/themes/`. Los 61 ids, los nombres y los 16 slots de cada
/// variante son los del escritorio sin renombrar nada: la elección de tema es
/// la misma clave en las dos apps, así que un id no se traduce ni se reordena
/// de otra manera.
///
/// ## Dónde está el `ThemeData`
/// No acá. Este archivo es del mismo tipo que `tokens.dart` — datos puros, sin
/// `BuildContext` ni `Theme` — y el `ThemeData` lo arma `AppTheme.variantOf` en
/// `theme.dart`. Que haya un solo constructor de temas es lo que garantiza que
/// un tema con variante y `AppTheme.light()` compartan exactamente la misma
/// estructura (barras, hojas, tarjetas, tipografía) y no se diferencien más que
/// en la paleta.
///
/// ## Qué es literal y qué no
/// - **Literal**: la paleta de cada variante. No sale de los tokens y no
///   podría salir: `tokens.dart` es el chrome **monocromo** de la casa (gris;
///   el color real vive en el scope de diffs) y "Dracula" o "Gruvbox" son, por
///   definición, paletas ajenas. Estos 16 valores por tema son el dato, igual
///   que en el escritorio, donde tampoco se derivaron de los tokens sino del
///   `resolveTheme` de la web.
/// - **Derivado, nunca hardcodeado**: [ThemeVariantColors.surfaceHover] (la
///   mezcla de `surface-strong`/`border-strong` que produce `--surface-hover` en
///   el CSS) y [ThemeVariantColors.onColor] (el legible que va encima de un
///   acento). Se calculan igual que en el escritorio para que dos temas no
///   puedan divergir por una constante repetida.
/// - **De los tokens**: la estructura. Radios, espaciado, escala tipográfica,
///   alto de barras, radio de hoja y scrim salen de `tokens.dart` para todos los
///   temas, monocromo incluido, así que elegir una variante cambia los colores
///   y no el layout.
///
/// ## Lo que el port no trae, y por qué
/// - `customDefaults`, `toJson`/`fromJson` e `isCustom`: son el `ThemeCreator`
///   de la web, que crea paletas guardadas por el usuario. Acá no se crean
///   temas — Ajustes sólo elige un id de este catálogo — y lo que se persiste
///   es el id, no la paleta; serializarla sería un formato que nadie escribe.
/// - `toColorScheme`: el `ColorScheme` lo arma `AppTheme` una sola vez, para
///   que el camino de la variante y el de los tokens no puedan separarse.
/// - El `FlexThemeData` del escritorio: esta app no depende de
///   `flex_color_scheme` (`pubspec.yaml` no lo trae) y el escritorio lo usaba
///   sólo como `ThemeData` base. Acá la base es `ThemeData.light()/dark()`, la
///   de hoy, así que la variante no arrastra una paleta tonal ajena.
library;

import 'dart:ui' show Brightness, Color;

import 'package:flutter/foundation.dart' show immutable;

/// Tipo de una variante: fija el brillo de su paleta y la sección del selector.
enum ThemeVariantKind {
  light,
  dark;

  /// Valor serializable (id persistido en las prefs).
  String get wire => name;

  /// Brillo Material de la paleta.
  Brightness get brightness =>
      this == ThemeVariantKind.dark ? Brightness.dark : Brightness.light;

  /// Etiqueta humana para la UI (sin emojis).
  String get label => this == ThemeVariantKind.dark ? 'Oscuro' : 'Claro';

  /// Tolera `null` y basura: un tipo desconocido es `dark`, no un crash.
  static ThemeVariantKind fromWire(String? raw) =>
      raw == 'light' ? ThemeVariantKind.light : ThemeVariantKind.dark;
}

/// Paleta resuelta de una variante.
///
/// Los 16 slots son los que existen en el CSS del cliente desktop
/// (`--bg`, `--surface`, `--surface-strong`, `--border`, `--border-strong`,
/// `--text`, `--muted`, `--primary`, `--accent`, `--secondary`, `--danger`,
/// `--warning`, `--success`, `--info`, `--surface-strong` del código y
/// `--code-text`).
@immutable
class ThemeVariantColors {
  const ThemeVariantColors({
    required this.bg,
    required this.surface,
    required this.surfaceStrong,
    required this.border,
    required this.borderStrong,
    required this.text,
    required this.muted,
    required this.primary,
    required this.accent,
    required this.secondary,
    required this.danger,
    required this.warning,
    required this.success,
    required this.info,
    required this.codeBg,
    required this.codeText,
  });

  /// Fondo raíz de la app (`--bg`).
  final Color bg;

  /// Superficie base de paneles (`--surface`).
  final Color surface;

  /// Superficie fuerte: elementos, inputs, código (`--surface-strong`).
  final Color surfaceStrong;

  /// Borde base (`--border`).
  final Color border;

  /// Borde activo/fuerte (`--border-strong`).
  final Color borderStrong;

  /// Texto principal (`--text`).
  final Color text;

  /// Texto atenuado (`--muted`).
  final Color muted;

  /// Acento primario (`--primary`).
  final Color primary;

  /// Acento secundario (`--accent`).
  final Color accent;

  /// Secundario (`--secondary`).
  final Color secondary;

  /// Semántico de error (`--danger`). Con variante, el chrome deja de ser
  /// monocromo y éste es el `error` real del `ColorScheme` (el tema
  /// monocromo mantiene el gris del token `danger`).
  final Color danger;

  /// Semántico de aviso (`--warning`).
  final Color warning;

  /// Semántico de éxito (`--success`).
  final Color success;

  /// Semántico informativo (`--info`).
  final Color info;

  /// Fondo de bloques de código (`--surface-strong` del scope de código).
  final Color codeBg;

  /// Texto de código (`--code-text`).
  final Color codeText;

  /// Hover derivado: la misma mezcla que el `--surface-hover` de `tokens.css`.
  Color get surfaceHover =>
      Color.lerp(surfaceStrong, borderStrong, 0.5) ?? surfaceStrong;

  /// Texto legible sobre [color] (el de mayor contraste, blanco o negro).
  ///
  /// Se usa para `onPrimary`/`onSecondary`/`onError`: una paleta con acento
  /// claro necesita texto oscuro y una con acento oscuro necesita texto
  /// claro, y ningún token puede saber de antemano cuál de los dos.
  static Color onColor(Color color) {
    final luminance = color.computeLuminance();
    final whiteContrast = 1.05 / (luminance + 0.05);
    final blackContrast = (luminance + 0.05) / 0.05;
    return blackContrast >= whiteContrast
        ? const Color(0xFF0A0A0A)
        : const Color(0xFFFFFFFF);
  }

  /// Los colores con los que se previsualiza la paleta en el selector: fondo,
  /// marco, acento primario y acento secundario. Mismo criterio que el
  /// `ThemePicker` del escritorio, para que el ojo reconozca la variante.
  List<Color> get swatch => <Color>[bg, surfaceStrong, primary, accent];
}

/// Variante de tema: nombre, tipo y paleta.
@immutable
class ThemeVariant {
  const ThemeVariant({
    required this.id,
    required this.name,
    required this.kind,
    required this.colors,
  });

  /// Id estable (persistido en las prefs; `"<tema>-light"` para las paletas
  /// claras, igual que en el escritorio).
  final String id;

  /// Nombre humano para la UI.
  final String name;

  /// Tipo (brillo de la paleta y sección del selector).
  final ThemeVariantKind kind;

  /// Paleta de la variante.
  final ThemeVariantColors colors;

  /// `'Claro'`/`'Oscuro'`.
  String get kindLabel => kind.label;
}

